/** Real HTTP source/fresh-package Meter journey. No substitute components or mocked browser APIs. */
import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
const output = process.env.CHARTS_PROOF_DIR
assert.ok(output, 'Retain Meter proof outside the checkout')
await mkdir(output, {recursive:true})
const server = spawn(process.execPath, ['tests/fixtures/charts-browser-smoke.mjs', ...process.argv.slice(2)], {stdio:['ignore','pipe','pipe']})
const logs=[],checks=[]
server.stdout.on('data', data=>logs.push(String(data)));server.stderr.on('data', data=>logs.push(String(data)))
let browser,page,base
// The clip is the painted interval on the real track; it does not resize or rescale the hatch texture.
const painted = locator => locator.evaluate(node=>{
 const style=getComputedStyle(node),box=node.getBoundingClientRect(),match=style.clipPath.match(/^inset\((.*?)(?: round|\))/)
 const sides=match?.[1].trim().split(/\s+/).map(parseFloat)
 return {clip:style.clipPath,left:sides?.[3]??sides?.[1],right:sides?.[1],width:box.width*(1-((sides?.[1]??100)+(sides?.[3]??sides?.[1]??0))/100),track:box.width,background:style.backgroundImage,color:style.backgroundColor,motion:style.transitionDuration}
})
const near=(actual,expected,message)=>assert.ok(Math.abs(actual-expected)<.1,`${message}: ${actual} vs ${expected}`)
try {
 const deadline=Date.now()+180000
 while(true){
  const ready=logs.join('').split('\n').slice(0,-1).find(line=>line.startsWith('{"consumer":'))
  if(ready){const identity=JSON.parse(ready);base=identity.url;await writeFile(`${output}/consumer.json`,JSON.stringify(identity,null,2));break}
  assert.ok(Date.now()<deadline&&server.exitCode===null,logs.join(''))
  await new Promise(resolve=>setTimeout(resolve,250))
 }
 browser=await chromium.launch({headless:true})
 for(const theme of ['light','dark'])for(const width of [1512,390]){
  const began=Date.now(),context=await browser.newContext({viewport:{width,height:982},colorScheme:theme,recordVideo:{dir:output,size:{width,height:982}}})
  page=await context.newPage();const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`${base}/?id=meter-modes&nonzero-motion=1&globals=agent-${theme}`)
  const mode=id=>page.locator(`[data-meter-case="${id}"]`),meter=id=>mode(id).locator('.ov-meter'),bar=(id,label)=>meter(id).locator(`.ov-meter-track > [data-segment="${label}"]`)
  await meter('compare').waitFor()
  assert.equal(await meter('compare').getAttribute('data-compact'),'true','old package must fail: compact is the shared public layout')
  const layout=await meter('compare').evaluate(node=>({cols:getComputedStyle(node).gridTemplateColumns,track:node.querySelector('.ov-meter-track').getBoundingClientRect().top,text:node.querySelector('.ov-meter-text').getBoundingClientRect().top,key:getComputedStyle(node.querySelector('.ov-meter-key')).display}))
  assert.equal(layout.cols.split(' ').length,2);assert.ok(Math.abs(layout.track-layout.text)<=10);assert.equal(layout.key,'none')
  await page.emulateMedia({reducedMotion:'reduce'})
  assert.equal((await painted(bar('compare','Recorded work'))).motion,'0s','reduced motion overrides even an explicitly nonzero consumer motion token')
  await page.emulateMedia({reducedMotion:'no-preference'})
  assert.equal(await mode('used').locator('.ov-meter-text').innerText(),'4 of 10 · 40%')
  near((await painted(bar('used','Used'))).width/(await painted(bar('used','Used'))).track,.4,'default used/total paint')
  assert.match(await mode('parts').innerText(),/Missing span\s+not recorded/)
  assert.match(await mode('parts').innerText(),/untraced\s+5 · 50%/)
  assert.equal(await bar('parts','Idle').getAttribute('data-hatched'),'true')
  assert.equal(await bar('legacy-untraced','Missing interval').getAttribute('data-hatched'),'true')
  const work=await painted(bar('compare','Recorded work')),open=await painted(bar('compare','Open turn'))
  near(work.left,0,'work begins at zero');near(work.right,70,'three units on ten-unit comparative scale')
  near(open.left,30,'open begins after work');near(open.right,60,'one measured open unit ends at four, not scale maximum')
  assert.match(open.background,/repeating-linear-gradient/);assert.notEqual(open.color,'rgba(0, 0, 0, 0)')
  assert.equal(await meter('compare').locator('[data-segment="untraced"]').count(),0,'unused comparative scale is plain, never an invented untraced part')
  assert.equal(await mode('compare').locator('.ov-meter-text').innerText(),'4 h')
  assert.match(await meter('compare').getAttribute('aria-label'),/4 h of 4 h accounted · 100% · scale maximum 10 h/)
  assert.match(await meter('compare').getAttribute('aria-label'),/Open turn: 1 h · 25%/)
  near((await painted(bar('partial','untraced'))).left,30,'only recorded remainder is untraced');near((await painted(bar('partial','untraced'))).right,60,'remainder ends at recorded total')
  assert.equal(await mode('unknown-total').locator('.ov-meter-track').getAttribute('data-hatched'),'true')
  near((await painted(bar('unknown-total','Recorded work'))).width,0,'unknown whole is not inferred from recorded parts')
  assert.equal(await mode('unknown-compact').locator('.ov-meter-text').innerText(),'—')
  assert.match(await meter('unknown-compact').getAttribute('aria-label'),/total not recorded.*Absent trace: not recorded/)
  assert.equal(await mode('zero').locator('.ov-meter-text').innerText(),'0')
  assert.equal(await meter('zero').locator('.ov-meter-track').getAttribute('data-hatched'),null)
  assert.doesNotMatch(await meter('zero').getAttribute('aria-label'),/not recorded|untraced/)
  assert.equal(await mode('zero-used').locator('.ov-meter-text').innerText(),'0')
  assert.equal(await mode('unknown-used').locator('.ov-meter-text').innerText(),'—')
  assert.equal(await mode('zero-whole').locator('.ov-meter-text').innerText(),'0 of 0 · —')
  await mode('steps').getByRole('list',{name:'Build checks'}).waitFor()
  assert.equal(await mode('steps').locator('[aria-current="step"]').innerText(),'2\nStuck\nOffline build')
  assert.match(await mode('invalid-axis').innerText(),/scaleMax must be finite, positive and at least the recorded total/)
  assert.match(await mode('invalid-nonfinite-axis').innerText(),/scaleMax must be finite, positive/)
  assert.match(await mode('over-total').innerText(),/Segments sum to 5, more than the total 4/)
  await meter('compare').hover()
  const readout=meter('compare').getByRole('tooltip')
  await readout.waitFor();assert.match(await readout.innerText(),/scale maximum 10 h[\s\S]*Open turn\s+1 h · 25%/)
  await page.mouse.move(0,0);assert.equal(await readout.count(),0)
  await mode('parts').locator('.ov-meter-track').click()
  await page.keyboard.press('Tab')
  assert.equal(await meter('compare').evaluate(node=>node===document.activeElement),true,'compact readout is reached through the native tab order')
  await readout.waitFor();assert.match(await readout.innerText(),/Recorded work\s+3 h · 75%/)
  await page.keyboard.press('Escape');assert.equal(await readout.count(),0)
  await page.keyboard.press('Tab');await meter('partial').getByRole('tooltip').waitFor()
  assert.match(await meter('partial').getByRole('tooltip').innerText(),/Absent trace\s+not recorded[\s\S]*untraced\s+1 · 25%/)
  await page.keyboard.press('Tab');await meter('unknown-compact').getByRole('tooltip').waitFor()
  await meter('long').focus();await meter('long').getByRole('tooltip').waitFor()
  assert.match(await meter('long').getByRole('tooltip').innerText(),/abcdefghijklmnopqrstuvwxyz0123456789/)
  const fit=await meter('long').getByRole('tooltip').evaluate(node=>{const box=node.getBoundingClientRect();return {left:box.left,right:box.right,font:parseFloat(getComputedStyle(node).fontSize),wrap:getComputedStyle(node).overflowWrap}})
  assert.ok(fit.left>=0&&fit.right<=width+1&&fit.font>=13);assert.equal(fit.wrap,'anywhere')
  await page.screenshot({path:`${output}/meter-focus-${width}-${theme}.png`,fullPage:true})
  await page.getByRole('button',{name:'Update recorded values'}).click()
  assert.equal(await mode('compare').locator('.ov-meter-text').innerText(),'8 h')
  await page.waitForFunction(()=>{const clip=getComputedStyle(document.querySelector('[data-meter-case="compare"] .ov-meter-track > span')).clipPath;const right=Number.parseFloat(clip.split(' ')[1]);return right>30&&right<70})
  const moving=await painted(bar('compare','Recorded work'))
  assert.notEqual(moving.motion,'0s','Brand stream motion is active')
  assert.ok(moving.right>30&&moving.right<70,`live recorded growth interpolates its painted interval: ${moving.clip}`)
  await page.waitForFunction(()=>Number.parseFloat(getComputedStyle(document.querySelector('[data-meter-case="compare"] .ov-meter-track > span')).clipPath.split(' ')[1])===30)
  near((await painted(bar('compare','Open turn'))).left,70,'measured open tail follows work after update')
  await meter('compare').focus();assert.match(await meter('compare').getByRole('tooltip').innerText(),/7 h · 88%/)
  await page.emulateMedia({reducedMotion:'reduce'})
  assert.equal((await painted(bar('compare','Recorded work'))).motion,'0s')
  await page.getByRole('button',{name:'Update recorded values'}).click()
  near((await painted(bar('compare','Recorded work'))).right,70,'reduced motion commits the same recorded geometry immediately')
  await meter('compare').focus();assert.match(await meter('compare').getByRole('tooltip').innerText(),/3 h · 75%/)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  assert.deepEqual(errors,[])
  await page.screenshot({path:`${output}/meter-reduced-${width}-${theme}.png`,fullPage:true})
  const scroller=mode('clipped').locator('[data-meter-scroll]')
  await scroller.scrollIntoViewIfNeeded();await scroller.evaluate(node=>node.scrollTop=node.scrollHeight)
  await meter('clipped').focus()
  const floating=meter('clipped').getByRole('tooltip');await floating.waitFor()
  assert.match(await floating.innerText(),/Recorded work at the last visible row\s+3 · 75%[\s\S]*Open turn\s+1 · 25%/)
  const overlay=await floating.evaluate(node=>{const b=node.getBoundingClientRect(),p=node.closest('[data-meter-scroll]').getBoundingClientRect();return {top:b.top,bottom:b.bottom,left:b.left,right:b.right,paneTop:p.top,paneBottom:p.bottom,native:node.matches(':popover-open')}})
  assert.equal(overlay.native,true,'the existing shared readout escapes transformed and clipped ancestors through the native top layer')
  assert.ok(overlay.top>=0&&overlay.bottom<=982&&overlay.left>=0&&overlay.right<=width,JSON.stringify(overlay))
  assert.ok(overlay.top<overlay.paneTop||overlay.bottom>overlay.paneBottom,'the full readout extends beyond the bounded scrolling pane')
  await page.screenshot({path:`${output}/meter-clipped-${width}-${theme}.png`})
  await page.getByRole('button',{name:'Update recorded values'}).focus()
  await floating.waitFor({state:'detached'})
  await meter('clipped').hover();await floating.waitFor()
  assert.equal(await floating.evaluate(node=>node.matches(':popover-open')),true,'pointer readout uses the same shared top layer')
  assert.match(await floating.innerText(),/Recorded work at the last visible row\s+3 · 75%/)
  await page.screenshot({path:`${output}/meter-clipped-hover-${width}-${theme}.png`})
  await page.waitForTimeout(Math.max(0,10100-(Date.now()-began)))
  await context.close();checks.push({theme,width,modes:17,result:'PASS',layout,work,open,fit,overlay})
 }
}catch(error){
 if(page&&!page.isClosed()){await page.screenshot({path:`${output}/failure.png`,fullPage:true});await writeFile(`${output}/failure.json`,JSON.stringify({error:String(error),text:await page.locator('body').innerText()},null,2))}
 throw error
}finally{await browser?.close();server.kill('SIGTERM');await writeFile(`${output}/consumer.log`,logs.join(''));await writeFile(`${output}/checks.json`,JSON.stringify(checks,null,2))}
console.log(JSON.stringify({result:'PASS',output,checks}))
