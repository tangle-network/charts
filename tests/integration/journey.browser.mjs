    assert.ok(tooltip.y >= plot.y && tooltip.y + tooltip.height <= plot.y + plot.height, 'A late virtual row tooltip stays beside the visible row')
    await page.locator('.ov-gantt-scroll').evaluate(el => { el.scrollTop -= 20 })
