    await page.getByRole('button', { name: `Agent ${agents - 1}`, exact: true }).press('Enter')
    assert.equal(await page.getByRole('button', { name: `Agent ${agents - 1}`, exact: true }).getAttribute('aria-pressed'), 'true')
