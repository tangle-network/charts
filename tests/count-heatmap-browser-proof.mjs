// Actual packed-package HTTP consumer: counts, unknowns, keyboard windows and live rendering.
import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { chromium } from 'playwright'
const out = resolve(process.env.COUNT_HEATMAP_EVIDENCE ?? '/tmp/count-heatmap-proof')
await mkdir(out,{recursive:true})
const child=spawn(process.execPath,['tests/fixtures/charts-browser-smoke.mjs',...process.argv.slice(2)],{env:{...process.env,PORT:'0'},stdio:['ignore','pipe','inherit']})
let output='', url=''
await new Promise((done,reject)=>{child.stdout.on('data',data=>{output+=data;const row=output.trim().split('\n').findLast(line=>line.startsWith('{')&&line.includes('"url":'));if(row){url=JSON.parse(row).url;done()}});child.on('exit',code=>reject(new Error(`consumer exited ${code}: ${output}`)))})
const browser=await chromium.launch({headless:true}), checks=[]
try {
 for(const theme of ['light','dark'])for(const width of [1512,390]){
  const context=await browser.newContext({viewport:{width,height:900},colorScheme:theme,recordVideo:{dir:out,size:{width,height:900}}}),page=await context.newPage(),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  try{
   await page.goto(`${url}/?id=analytics-counts&globals=theme:agent-${theme}`)
   const table=page.getByRole('table',{name:'Tool calls'})
   await table.waitFor()
   assert.equal(await table.getAttribute('aria-rowcount'),'141'); await page.getByRole('img',{name:'Recorded calls per 4 h',exact:true}).waitFor()
   assert.ok(await table.getByRole('row').count()<=23,'140 rows remain windowed')
   assert.match(await table.getByRole('row').nth(1).innerText(),/—/,'missing cells stay unknown')
   assert.match(await table.getByRole('row').nth(2).innerText(),/\b0\b/,'recorded zero is visible')
   const first=table.getByRole('button',{name:'Agent 0',exact:true})
   await first.focus()
   for(let i=0;i<120;i++)await page.keyboard.press('ArrowDown')
   assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Agent 120')
   await page.keyboard.press('Enter')
   assert.equal(await page.locator('output').innerText(),'agent-120')
   assert.ok(await table.getByRole('row').count()<=23)
   await table.getByRole('button',{name:'Agent 119',exact:true}).click()
   const pane=table.locator('.tgc-count-scroll'), scrollBefore=await pane.evaluate(node=>node.scrollTop)
   await pane.hover(); await page.mouse.wheel(0,32)
   await page.waitForFunction(old=>document.querySelector('.tgc-count-scroll').scrollTop!==old,scrollBefore)
   assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Agent 119','manual scrolling does not restore a consumed keyboard target')
   await page.getByRole('button',{name:'Append counts'}).focus()
   await pane.hover(); await page.mouse.wheel(0,-32); await page.waitForTimeout(100)
   assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Append counts','table scrolling preserves focus on another control')
   const old=await table.locator('[data-heat-row="120"][data-heat-column="1"]').innerText()
   const track=page.locator('.ov-hbar-track > span').first()
   const before=await track.evaluate(node=>getComputedStyle(node).transform)
   await page.getByRole('button',{name:'Append counts'}).click()
   await page.waitForFunction(old=>document.querySelector('[data-heat-row="120"][data-heat-column="1"]').textContent!==old,old)
   const during=await track.evaluate(node=>getComputedStyle(node).transitionDuration)
   assert.notEqual(during,'0s','Brand stream motion applies')
   await page.waitForTimeout(650)
   assert.notEqual(await track.evaluate(node=>getComputedStyle(node).transform),before)
   assert.match(await page.locator('.ov-hbar-track > span').nth(1).getAttribute('style'),/scaleX\(0\)/)
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
   await page.screenshot({path:`${out}/${theme}-${width}.png`,fullPage:true})
   await page.emulateMedia({reducedMotion:'reduce'})
   assert.equal(await track.evaluate(node=>getComputedStyle(node).transitionDuration),'0s')
   checks.push({theme,width,result:'PASS',rows:140,mountedRows:await table.getByRole('row').count(),selected:'agent-120',before:old,after:await table.locator('[data-heat-row="120"][data-heat-column="1"]').innerText(),motion:during})
   await page.emulateMedia({reducedMotion:'no-preference'})
   await page.goto(`${url}/?id=progress-lines&globals=theme:agent-${theme}`)
   const lines=page.locator('svg[aria-label="Best so far, Checked releases"]')
   await lines.waitFor()
   assert.match(await lines.textContent(), /3 · Hidden test set/)
   assert.equal(await lines.locator('.ov-line-point').count(),3)
   assert.equal(await lines.locator('[data-highlight]').count(),1)
   const vertices=(await lines.locator('polyline').getAttribute('points')).split(' ').map(s=>s.split(',').map(Number))
   assert.equal(vertices.length,5)
   assert.equal(vertices[0][1],vertices[1][1],'prior level holds until the next recorded release')
   assert.equal(vertices[1][0],vertices[2][0],'step gain is vertical at the release time')
   await lines.getByRole('link',{name:'rc2: 2',exact:true}).focus()
   assert.match(await page.getByRole('tooltip').innerText(),/rc2\s+2/,'simultaneous release readout keeps the focused observation')
   assert.equal(await lines.locator('circle:not(.ov-line-point)').count(),0,'a crosshair marker never covers keyboard focus')
   await page.keyboard.press('Enter')
   await page.waitForURL(/release=rc2/)
   assert.equal(await page.locator('output').innerText(),'rc2')
   await page.getByRole('button',{name:'Append release'}).click()
   await page.waitForFunction(()=>document.querySelectorAll('.ov-line-point').length===4)
   await page.waitForTimeout(30)
   assert.equal(await page.locator('[data-highlight]').getAttribute('cy'),await page.locator('.ov-line-point').last().getAttribute('cy'))
   assert.notEqual(await page.locator('.ov-line-point').last().evaluate(n=>getComputedStyle(n).transitionDuration),'0s')
   await page.screenshot({path:`${out}/lines-${theme}-${width}.png`,fullPage:true})
   await page.emulateMedia({reducedMotion:'reduce'})
   assert.equal(await page.locator('.ov-line-point').last().evaluate(n=>getComputedStyle(n).transitionDuration),'0s')
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
   assert.deepEqual(errors,[])
  } finally {await context.close()}
 }
 await writeFile(`${out}/checks.json`,JSON.stringify(checks,null,2)+'\n')
}finally{await browser.close();child.kill('SIGTERM')}
console.log(JSON.stringify({result:'PASS',out,checks}))
